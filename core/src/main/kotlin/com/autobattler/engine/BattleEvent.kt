package com.autobattler.engine

import com.autobattler.model.*

/**
 * Represents a single action taken by a unit during battle simulation.
 * Each event carries unit IDs for animation mapping.
 */
sealed class BattleEvent {
    data class Move(
        val unitId: Int,
        val unitName: String,
        val from: Position,
        val to: Position
    ) : BattleEvent()

    data class Attack(
        val attackerId: Int,
        val attackerName: String,
        val attackerPos: Position,
        val targetId: Int,
        val targetName: String,
        val targetPos: Position,
        val damage: Int,
        val targetHpAfter: Int,
        val attackerType: UnitType
    ) : BattleEvent()

    data class Heal(
        val healerId: Int,
        val healerName: String,
        val targetId: Int,
        val targetName: String,
        val targetPos: Position,
        val amount: Int,
        val targetHpAfter: Int
    ) : BattleEvent()

    data class Death(val unitId: Int, val unitName: String) : BattleEvent()

    data class TurnStart(val turnNumber: Int) : BattleEvent()

    /** A Farmer successfully planted a Farm structure. */
    data class FarmPlanted(
        val farmerId: Int,
        val farmerName: String,
        val position: Position,
        val farmId: Int
    ) : BattleEvent()

    /** A Farm generated gold this turn. */
    data class FarmGold(
        val farmId: Int,
        val position: Position,
        val amount: Int
    ) : BattleEvent()

    /** A single unit caught in a fireball blast. */
    data class FireballHit(
        val unitId: Int,
        val unitName: String,
        val unitPos: Position,
        val damage: Int,
        val hpAfter: Int
    )

    /**
     * Wizard fires a fireball aimed at [targetTile].
     * Every unit whose footprint overlaps the blast area (Chebyshev distance ≤ [radius]
     * from [targetTile]) is damaged — friend and foe alike.
     */
    data class Fireball(
        val casterId: Int,
        val casterName: String,
        val casterPos: Position,
        val casterType: UnitType,
        val targetTile: Position,
        val radius: Int,
        val hits: List<FireballHit>
    ) : BattleEvent()
}

/**
 * The outcome of a completed battle.
 * [farmGoldEarned] tracks total gold generated by Farm structures during the battle.
 */
data class BattleOutcome(
    val winner: Winner,
    val events: List<BattleEvent>,
    val totalTurns: Int,
    val farmGoldEarned: Int = 0
) {
    enum class Winner { PLAYER, ENEMY, DRAW }
}
