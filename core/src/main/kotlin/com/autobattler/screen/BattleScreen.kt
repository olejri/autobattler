/**
 * Main battle screen handling three phases in a single unified view:
 *
 * 1. SETUP   — Player sees enemy placements, drags units from the roster bar
 *              (below the map) onto their side, spending gold.
 * 2. BATTLE  — Events replay with animated unit movement.
 * 3. RESULT  — Outcome shown with retry/next options.
 *
 * When [commander] is provided the screen is in campaign mode:
 * the shop is filtered to unlocked units, and a win awards XP + gold to the Commander.
 */
class BattleScreen(
    private val game: AutobattlerGame,
    private val scenario: ScenarioDefinition,
    private val commander: Commander? = null,
    private val boughtRoster: List<UnitType>? = null  // null = buy phase active
) : ScreenAdapter() {

    private enum class Phase { SETUP, BATTLE, RESULT }

    // ─── Core state ─────────────────────────────────────────────────────────────
    private val grid = BattleGrid()
    private val engine = GridBattleEngine()

    // Index within tutorialSequence (-1 if campaign or standalone scenario)
    private val tutorialIndex = Scenarios.tutorialSequence.indexOf(scenario)

    // ─── Rendering ──────────────────────────────────────────────────────────────
    private val shapeRenderer = ShapeRenderer()
    private val batch = SpriteBatch()
    // Fonts created lazily in show() after GL context is ready
    private lateinit var font: BitmapFont
    private lateinit var bigFont: BitmapFont
    private val stage = Stage(ScreenViewport())

    // ─── Grid layout ─────────────────────────────────────────────────────────────
    // gridOffsetX leaves 220px on the left for the CommanderPanel sidebar
    private val cellSize = 48f
    private val gridOffsetX = 220f
    private val gridOffsetY = 185f   // leaves 185px at bottom for roster bar

    // ─── SETUP state ────────────────────────────────────────────────────────────
    private var phase = Phase.SETUP

    /** Starting gold: commander's persistent pool in campaign mode, scenario budget in tutorial. */
    private val initialGold = commander?.gold ?: scenario.startingGold
    private var gold = initialGold

    // Units available in the shop — filtered by unlocked types in campaign mode
    private val shopTypes = if (commander != null)
        UnitType.purchasable.filter { it.id in commander.unlockedUnitTypeIds }
    else
        listOf(NormalUnitType.Melee, NormalUnitType.Ranged, NormalUnitType.Healer)

    // Campaign result — computed on victory, committed when player clicks Continue
    private var updatedCommander: Commander? = null

    // Track how many enemy units were killed (for gold drops)
    private var enemyKillCount = 0
    // Track gold generated by Farm structures during battle
    private var farmGoldEarned = 0

    companion object {
        const val GOLD_PER_KILL     = 10
        const val BATTLE_BONUS_GOLD = 200  // included in scenario.goldReward
    }

    /** Units available to drag onto the map (counts per type). */
    private val rosterPool: MutableMap<UnitType, Int> =
        shopTypes.associateWith { 0 }.toMutableMap()

    // Commander panel widget — shown top-right in campaign mode
    private var commanderWidget: CommanderPanel? = null

    // Drag-and-drop state
    private var draggingType: UnitType? = null
    private var dragScreenX = 0f
    private var dragScreenY = 0f
    private var isDragging = false

    // Grid cell highlight under cursor during drag
    private var hoverGridX = -1
    private var hoverGridY = -1

    /** Units the player has placed (to allow removal/refund). */
    private val placedPlayerUnitIds = mutableListOf<Int>()

    private var nextUnitId = 1

    // ─── Animation state ────────────────────────────────────────────────────────
    private val renderPositions = mutableMapOf<Int, Vector2>()
    private val renderHp = mutableMapOf<Int, Int>()
    private val renderCooldown = mutableMapOf<Int, Int>()   // current cooldownTimer per unit
    private val deadUnits = mutableSetOf<Int>()
    private val allUnitsById = mutableMapOf<Int, BattleUnit>()

    // ─── Playback speed ─────────────────────────────────────────────────────────
    private enum class PlaybackSpeed(val label: String, val multiplier: Float) {
        SLOW("Slow", 1f), FASTER("Faster", 2f), FASTEST("Fastest", 4f)
    }
    private var playbackSpeed = PlaybackSpeed.SLOW

    // ─── Battle playback ────────────────────────────────────────────────────────
    private var battleOutcome: BattleOutcome? = null
    private var battleEvents: List<BattleEvent> = emptyList()
    private var currentEventIndex = 0
    private var eventTimer = 0f
    private val eventDelay   get() = 0.5f / playbackSpeed.multiplier
    private val animDuration get() = 0.2f / playbackSpeed.multiplier

    private var animating = false
    private var animUnitId = -1
    private var animFrom = Vector2()
    private var animTo = Vector2()
    private var animProgress = 0f

    // ─── Flash effects ──────────────────────────────────────────────────────────
    private var flashUnitId = -1
    private var flashTimer = 0f
    private var flashColor = Color.WHITE

    // ─── Battle effects & log ───────────────────────────────────────────────────
    private val battleEffects = BattleEffects()
    private val battleLog = mutableListOf<String>()

    // ─── Roster bar layout ───────────────────────────────────────────────────────
    private val rosterBarY = 10f
    private val rosterBarH = 160f
    private val rosterSlotSize = 110f
    private val rosterStartX = gridOffsetX  // left-aligned under the grid


    // ─── Lifecycle ──────────────────────────────────────────────────────────────

    override fun show() {
        Gdx.input.inputProcessor = InputMultiplexer(stage, createInputProcessor())

        // Create crisp FreeType fonts — must be after GL context is ready
        font = Fonts.create(18, borderWidth = 1f)
        bigFont = Fonts.create(28, borderWidth = 1.5f)

        // Load map
        if (scenario.mapPath != null) {
            try {
                val mapDef = MapLoader.loadMap(scenario.mapPath)
                MapLoader.applyToGrid(mapDef, grid)
            } catch (e: Exception) {
                MapLayouts.applyTutorialLayout(grid)
            }
        } else {
            MapLayouts.applyTutorialLayout(grid)
        }

        // Place enemy units
        for ((type, pos) in scenario.enemyPlacements) {
            val unit = BattleUnit(id = nextUnitId++, type = type, owner = BattleUnit.Owner.ENEMY, position = pos)
            grid.placeUnit(unit)
            registerUnit(unit)
        }

        // If bypassing buy (dev quick-test), pre-populate the rosterPool from scenario default
        if (boughtRoster != null) {
            for (type in boughtRoster) {
                rosterPool[type] = (rosterPool[type] ?: 0) + 1
            }
        }

        // Commander panel — pinned to the LEFT side, consistent with CampaignScreen
        if (commander != null) {
            commanderWidget = CommanderPanel(commander)
            val panelContainer = Table()
            panelContainer.setFillParent(true)
            panelContainer.top().left()
            panelContainer.add(commanderWidget!!).width(210f).fillY()
            stage.addActor(panelContainer)
        }

        rebuildUI()
    }

    private fun registerUnit(unit: BattleUnit) {
        allUnitsById[unit.id] = unit
        renderPositions[unit.id] = Vector2(unit.position.x.toFloat(), unit.position.y.toFloat())
        renderHp[unit.id] = unit.currentHp
    }

    // ─── Render ─────────────────────────────────────────────────────────────────

    override fun render(delta: Float) {
        Gdx.gl.glClearColor(0.06f, 0.06f, 0.1f, 1f)
        Gdx.gl.glClear(GL20.GL_COLOR_BUFFER_BIT)

        if (phase == Phase.BATTLE) updateBattleAnimation(delta)
        if (flashTimer > 0f) flashTimer -= delta
        battleEffects.update(delta)

        drawGrid()
        drawUnits()

        Gdx.gl.glEnable(GL20.GL_BLEND)
        Gdx.gl.glBlendFunc(GL20.GL_SRC_ALPHA, GL20.GL_ONE_MINUS_SRC_ALPHA)
        battleEffects.render(shapeRenderer)
        Gdx.gl.glDisable(GL20.GL_BLEND)

        if (phase == Phase.SETUP) {
            drawRosterBar()
            drawDragGhost()
        }

        drawHUD()

        stage.act(delta)
        stage.draw()
    }

    // ─── Grid drawing ───────────────────────────────────────────────────────────

    private fun drawGrid() {
        shapeRenderer.begin(ShapeRenderer.ShapeType.Filled)
        for (x in 0 until grid.width) {
            for (y in 0 until grid.height) {
                val sx = gridOffsetX + x * cellSize
                val sy = gridOffsetY + y * cellSize
                val tile = grid.getTile(x, y)
                shapeRenderer.color = getTileColor(tile, x)
                shapeRenderer.rect(sx, sy, cellSize, cellSize)

                when (tile) {
                    TileType.WATER -> {
                        shapeRenderer.color = Color(0.15f, 0.3f, 0.55f, 1f)
                        val wo = ((x + y) % 3) * 4f
                        shapeRenderer.rect(sx + 4f + wo, sy + cellSize / 2 - 1f, cellSize * 0.4f, 2f)
                    }
                    TileType.ROCK -> {
                        shapeRenderer.color = Color(0.35f, 0.32f, 0.28f, 1f)
                        shapeRenderer.circle(sx + cellSize / 2, sy + cellSize / 2, cellSize * 0.3f)
                        shapeRenderer.color = Color(0.45f, 0.42f, 0.38f, 1f)
                        shapeRenderer.circle(sx + cellSize / 2 - 2f, sy + cellSize / 2 + 2f, cellSize * 0.18f)
                    }
                    TileType.BRIDGE -> {
                        shapeRenderer.color = Color(0.5f, 0.35f, 0.15f, 1f)
                        for (i in 0..3) {
                            val py = sy + 4f + i * (cellSize - 8f) / 3f
                            shapeRenderer.rect(sx + 3f, py, cellSize - 6f, 3f)
                        }
                    }
                    TileType.TREE -> {
                        shapeRenderer.color = Color(0.35f, 0.22f, 0.08f, 1f)
                        shapeRenderer.rect(sx + cellSize / 2 - 3f, sy + 2f, 6f, cellSize * 0.4f)
                        shapeRenderer.color = Color(0.1f, 0.4f, 0.12f, 1f)
                        shapeRenderer.circle(sx + cellSize / 2, sy + cellSize * 0.65f, cellSize * 0.32f)
                        shapeRenderer.color = Color(0.15f, 0.5f, 0.15f, 1f)
                        shapeRenderer.circle(sx + cellSize / 2 - 3f, sy + cellSize * 0.7f, cellSize * 0.2f)
                    }
                    else -> {}
                }
            }
        }

        // Hover highlight during drag
        if (isDragging && hoverGridX in 0..BattleGrid.PLAYER_ZONE_END && hoverGridY in 0 until grid.height) {
            val pos = Position(hoverGridX, hoverGridY)
            val canPlace = draggingType != null && grid.getTile(pos).placeable && !grid.isOccupied(pos)
            shapeRenderer.color = if (canPlace) Color(0.3f, 0.7f, 0.3f, 0.5f) else Color(0.7f, 0.2f, 0.2f, 0.4f)
            shapeRenderer.rect(
                gridOffsetX + hoverGridX * cellSize + 1,
                gridOffsetY + hoverGridY * cellSize + 1,
                cellSize - 2, cellSize - 2
            )
        }
        shapeRenderer.end()

        // Grid lines
        shapeRenderer.begin(ShapeRenderer.ShapeType.Line)
        shapeRenderer.color = Color(0.2f, 0.2f, 0.25f, 1f)
        for (x in 0..grid.width) {
            val sx = gridOffsetX + x * cellSize
            shapeRenderer.line(sx, gridOffsetY, sx, gridOffsetY + grid.height * cellSize)
        }
        for (y in 0..grid.height) {
            val sy = gridOffsetY + y * cellSize
            shapeRenderer.line(gridOffsetX, sy, gridOffsetX + grid.width * cellSize, sy)
        }
        shapeRenderer.end()
    }

    private fun getTileColor(tile: TileType, x: Int): Color = when (tile) {
        TileType.GRASS -> if (x <= BattleGrid.PLAYER_ZONE_END) Color(0.08f, 0.16f, 0.08f, 1f) else Color(0.16f, 0.08f, 0.08f, 1f)
        TileType.WATER -> Color(0.08f, 0.15f, 0.35f, 1f)
        TileType.ROCK -> Color(0.25f, 0.22f, 0.2f, 1f)
        TileType.BRIDGE -> Color(0.35f, 0.25f, 0.1f, 1f)
        TileType.TREE -> Color(0.05f, 0.12f, 0.05f, 1f)
    }

    // ─── Unit drawing ───────────────────────────────────────────────────────────

    private fun drawUnits() {
        shapeRenderer.begin(ShapeRenderer.ShapeType.Filled)
        for ((unitId, renderPos) in renderPositions) {
            if (unitId in deadUnits) continue
            val unit = allUnitsById[unitId] ?: continue
            val uc = unit.size.toFloat()
            val cx = gridOffsetX + renderPos.x * cellSize + cellSize * uc / 2
            val cy = gridOffsetY + renderPos.y * cellSize + cellSize * uc / 2
            val radius = cellSize * uc * 0.42f

            var color = when (unit.owner) {
                BattleUnit.Owner.PLAYER  -> Color(0.2f, 0.6f, 1f, 0.6f)
                BattleUnit.Owner.ENEMY   -> Color(1f, 0.3f, 0.2f, 0.6f)
                BattleUnit.Owner.NATURAL -> Color(0.6f, 0.45f, 0.1f, 0.6f)  // amber — neutral predator
            }
            if (unitId == flashUnitId && flashTimer > 0f) {
                val t = flashTimer / 0.3f
                color = Color(MathUtils.lerp(color.r, flashColor.r, t), MathUtils.lerp(color.g, flashColor.g, t), MathUtils.lerp(color.b, flashColor.b, t), 1f)
            }
            shapeRenderer.color = color
            shapeRenderer.circle(cx, cy, radius)
            shapeRenderer.color = Color(0.08f, 0.08f, 0.12f, 1f)
            shapeRenderer.circle(cx, cy, radius - 3f)

            val hp = renderHp[unitId] ?: unit.currentHp
            val barW = cellSize * uc - 6f
            val barH = 5f
            val bx = gridOffsetX + renderPos.x * cellSize + 3f
            val by = gridOffsetY + renderPos.y * cellSize + cellSize * uc - 8f
            shapeRenderer.color = Color(0.15f, 0.15f, 0.15f, 1f)
            shapeRenderer.rect(bx, by, barW, barH)
            val hp01 = hp.toFloat() / unit.type.maxHp
            shapeRenderer.color = when { hp01 > 0.6f -> Color(0.2f, 0.8f, 0.2f, 1f); hp01 > 0.3f -> Color(0.9f, 0.8f, 0.1f, 1f); else -> Color(0.9f, 0.2f, 0.2f, 1f) }
            shapeRenderer.rect(bx, by, barW * hp01, barH)

            // Cooldown / readiness bar (battle phase only; skip structures which never act)
            if (phase == Phase.BATTLE && !unit.type.isStructure) {
                val maxCd = unit.type.cooldown
                val curCd = renderCooldown[unitId] ?: 0
                val ready01 = if (maxCd <= 0) 1f else (maxCd - curCd).toFloat() / maxCd
                val cby = by - 6f
                shapeRenderer.color = Color(0.1f, 0.1f, 0.1f, 1f)
                shapeRenderer.rect(bx, cby, barW, 4f)
                shapeRenderer.color = if (ready01 >= 1f) Color(1f, 0.85f, 0f, 1f) else Color(0.2f, 0.75f, 0.9f, 1f)
                shapeRenderer.rect(bx, cby, barW * ready01, 4f)
            }

            // In setup phase: show remove [X] indicator on placed player units
            if (phase == Phase.SETUP && unit.owner == BattleUnit.Owner.PLAYER) {
                shapeRenderer.color = Color(0.8f, 0.2f, 0.2f, 0.7f)
                shapeRenderer.circle(gridOffsetX + renderPos.x * cellSize + cellSize - 6f, gridOffsetY + renderPos.y * cellSize + cellSize - 6f, 6f)
            }
        }
        shapeRenderer.end()

        batch.begin()
        for ((unitId, renderPos) in renderPositions) {
            if (unitId in deadUnits) continue
            val unit = allUnitsById[unitId] ?: continue
            val uc = unit.size.toFloat()
            val ss = cellSize * uc - 8f
            val sx = gridOffsetX + renderPos.x * cellSize + (cellSize * uc - ss) / 2
            val sy = gridOffsetY + renderPos.y * cellSize + (cellSize * uc - ss) / 2 - 2f
            batch.setColor(when (unit.owner) {
                BattleUnit.Owner.ENEMY   -> Color(1f, 0.6f, 0.6f, 1f)
                BattleUnit.Owner.NATURAL -> Color(0.9f, 0.8f, 0.5f, 1f)  // warm tint for wildlife
                else                     -> Color.WHITE
            })
            batch.draw(SpriteGenerator.getTexture(unit.type), sx, sy, ss, ss)
        }
        batch.setColor(Color.WHITE)
        batch.end()
    }

    // ─── Roster bar (setup phase only) ──────────────────────────────────────────

    private fun drawRosterBar() {
        val barX = rosterStartX
        val barY = rosterBarY
        val barW = grid.width * cellSize
        val barH = rosterBarH

        // Background
        shapeRenderer.begin(ShapeRenderer.ShapeType.Filled)
        shapeRenderer.color = Color(0.08f, 0.1f, 0.08f, 1f)
        shapeRenderer.rect(barX, barY, barW, barH)
        shapeRenderer.end()

        shapeRenderer.begin(ShapeRenderer.ShapeType.Line)
        shapeRenderer.color = Color(0.3f, 0.5f, 0.3f, 0.8f)
        shapeRenderer.rect(barX, barY, barW, barH)
        shapeRenderer.end()

        // Slot for each purchasable type
        for ((i, type) in shopTypes.withIndex()) {
            val slotX = barX + i * (rosterSlotSize + 12f) + 12f
            val slotY = barY + (barH - rosterSlotSize) / 2

            val canAfford = gold >= type.cost
            val ownedCount = rosterPool[type] ?: 0

            // Slot background
            shapeRenderer.begin(ShapeRenderer.ShapeType.Filled)
            shapeRenderer.color = when {
                canAfford -> Color(0.12f, 0.2f, 0.12f, 1f)
                else -> Color(0.15f, 0.12f, 0.12f, 1f)
            }
            shapeRenderer.rect(slotX, slotY, rosterSlotSize, rosterSlotSize)
            shapeRenderer.end()

            shapeRenderer.begin(ShapeRenderer.ShapeType.Line)
            shapeRenderer.color = if (canAfford) Color(0.4f, 0.7f, 0.4f, 1f) else Color(0.35f, 0.3f, 0.3f, 1f)
            shapeRenderer.rect(slotX, slotY, rosterSlotSize, rosterSlotSize)
            shapeRenderer.end()

            // Unit icon
            batch.begin()
            batch.setColor(if (canAfford) Color.WHITE else Color(0.5f, 0.5f, 0.5f, 1f))
            val iconSize = rosterSlotSize - 28f
            val iconX = slotX + (rosterSlotSize - iconSize) / 2
            val iconY = slotY + 22f
            batch.draw(SpriteGenerator.getTexture(type), iconX, iconY, iconSize, iconSize)
            batch.setColor(Color.WHITE)

            // Cost label
            font.color = if (canAfford) Color.GOLD else Color.GRAY
            font.draw(batch, "${type.cost}g", slotX + 4f, slotY + 16f)

            // Name
            font.color = if (canAfford) Color.WHITE else Color.DARK_GRAY
            font.draw(batch, type.displayName, slotX + 4f, slotY + rosterSlotSize - 6f)

            // Unplaced count badge (units bought but not yet on map)
            if (ownedCount > 0) {
                font.color = Color.CYAN
                font.draw(batch, "×$ownedCount", slotX + rosterSlotSize - 22f, slotY + rosterSlotSize - 6f)
            }
            batch.end()
        }

        // Hints (gold is shown in the CommanderPanel on the left)
        batch.begin()
        font.color = Color.LIGHT_GRAY
        font.draw(batch, "Drag units onto the green side", barX + shopTypes.size * (rosterSlotSize + 12f) + 24f, barY + barH - 16f)
        font.draw(batch, "Click placed unit to refund",    barX + shopTypes.size * (rosterSlotSize + 12f) + 24f, barY + barH - 36f)
        batch.end()
    }

    // ─── Drag ghost ─────────────────────────────────────────────────────────────

    private fun drawDragGhost() {
        val type = draggingType ?: return

        val ghostSize = cellSize - 4f
        batch.begin()
        batch.setColor(1f, 1f, 1f, 0.75f)
        batch.draw(SpriteGenerator.getTexture(type), dragScreenX - ghostSize / 2, dragScreenY - ghostSize / 2, ghostSize, ghostSize)
        batch.setColor(Color.WHITE)
        batch.end()
    }

    // ─── HUD ────────────────────────────────────────────────────────────────────

    private fun drawHUD() {
        batch.begin()
        val hudX = gridOffsetX + grid.width * cellSize + 20f
        var hudY = Gdx.graphics.height - 30f

        bigFont.color = Color.WHITE
        bigFont.draw(batch, scenario.name, hudX, hudY)
        hudY -= 40f

        if (phase == Phase.SETUP) {
            // Enemy preview
            font.color = Color(1f, 0.5f, 0.5f, 1f)
            font.draw(batch, "Enemy:", hudX, hudY)
            hudY -= 22f
            for ((type, _) in scenario.enemyPlacements) {
                font.color = Color(1f, 0.7f, 0.7f, 1f)
                font.draw(batch, " • ${type.displayName} (HP:${type.maxHp} ATK:${type.power})", hudX, hudY)
                hudY -= 18f
            }
        } else {
            font.color = Color.GOLD
            font.draw(batch, "Battle Log:", hudX, hudY)
            hudY -= 22f
            for (line in battleLog.takeLast(22)) {
                font.color = when {
                    "──" in line -> Color(0.6f, 0.6f, 0.8f, 1f)
                    "deals" in line -> Color(1f, 0.6f, 0.5f, 1f)
                    "heals" in line -> Color(0.5f, 1f, 0.6f, 1f)
                    "died" in line -> Color(1f, 0.3f, 0.3f, 1f)
                    "moves" in line -> Color(0.7f, 0.7f, 0.7f, 1f)
                    else -> Color.WHITE
                }
                font.draw(batch, line, hudX, hudY)
                hudY -= 17f
            }
        }
        batch.end()
    }

    // ─── Battle animation ────────────────────────────────────────────────────────

    /**
     * Syncs the CommanderPanel gold display to the current in-battle gold value.
     * Called whenever gold changes: unit bought, unit refunded, or farm gold earned.
     */
    private fun refreshCommanderPanel() {
        val c = commander ?: return
        commanderWidget?.refresh(c.copy(gold = gold + farmGoldEarned))
    }

    private fun startBattle() {        phase = Phase.BATTLE
        battleOutcome = engine.simulate(grid)
        battleEvents = battleOutcome!!.events
        currentEventIndex = 0
        eventTimer = 0f
        animating = false
        battleLog.clear()
        // All units start the battle ready to act (cooldown = 0)
        renderCooldown.clear()
        allUnitsById.keys.forEach { renderCooldown[it] = 0 }
        val logPath = BattleLogger.log(grid, battleOutcome!!, scenario.name)
        Gdx.app.log("Autobattler", "Battle log saved: $logPath")
        rebuildUI()
    }

    private fun updateBattleAnimation(delta: Float) {
        if (animating) {
            animProgress += delta / animDuration
            if (animProgress >= 1f) {
                renderPositions[animUnitId] = Vector2(animTo)
                animating = false
                if (currentEventIndex < battleEvents.size) {
                    val next = battleEvents[currentEventIndex]
                    if (next is BattleEvent.Move && next.unitId == animUnitId) { applyNextEvent(); return }
                }
            } else {
                val t = smoothStep(animProgress)
                renderPositions[animUnitId] = Vector2(MathUtils.lerp(animFrom.x, animTo.x, t), MathUtils.lerp(animFrom.y, animTo.y, t))
            }
            return
        }
        if (battleEffects.isPlaying) return
        eventTimer += delta
        if (eventTimer >= eventDelay && currentEventIndex < battleEvents.size) { eventTimer = 0f; applyNextEvent() }
        if (currentEventIndex >= battleEvents.size && !animating && !battleEffects.isPlaying && phase == Phase.BATTLE) {
            phase = Phase.RESULT
            when (battleOutcome?.winner) {
                BattleOutcome.Winner.PLAYER -> SoundGenerator.getVictory().play(0.6f)
                BattleOutcome.Winner.ENEMY  -> SoundGenerator.getDefeat().play(0.6f)
                else                        -> SoundGenerator.getDefeat().play(0.4f)
            }
            // Count enemy kills for gold drops
            enemyKillCount = battleOutcome!!.events
                .filterIsInstance<BattleEvent.Death>()
                .count { allUnitsById[it.unitId]?.owner == BattleUnit.Owner.ENEMY }

            // Compute updated commander now, but only commit when player clicks Continue
            if (battleOutcome?.winner == BattleOutcome.Winner.PLAYER && commander != null) {
                val goldSpent  = initialGold - gold
                val goldEarned = enemyKillCount * GOLD_PER_KILL + scenario.goldReward + farmGoldEarned
                updatedCommander = commander.afterVictory(scenario.xpReward, goldEarned, goldSpent)
            }
            rebuildUI()
        }
    }

    private fun applyNextEvent() {
        if (currentEventIndex >= battleEvents.size) return
        when (val event = battleEvents[currentEventIndex++]) {
            is BattleEvent.TurnStart -> {
                battleLog.add("── Turn ${event.turnNumber} ──")
                // Tick all cooldown timers down by 1 (mirrors engine behaviour)
                for (id in renderCooldown.keys) {
                    renderCooldown[id] = ((renderCooldown[id] ?: 0) - 1).coerceAtLeast(0)
                }
            }
            is BattleEvent.Move -> {
                val isLast = currentEventIndex >= battleEvents.size || battleEvents[currentEventIndex] !is BattleEvent.Move
                    || (battleEvents[currentEventIndex] as BattleEvent.Move).unitId != event.unitId
                if (isLast) battleLog.add("${event.unitName} moves to (${event.to.x},${event.to.y})")
                animating = true; animUnitId = event.unitId
                animFrom = Vector2(event.from.x.toFloat(), event.from.y.toFloat())
                animTo = Vector2(event.to.x.toFloat(), event.to.y.toFloat()); animProgress = 0f
            }
            is BattleEvent.Attack -> {
                battleLog.add("${event.attackerName} deals ${event.damage} to ${event.targetName} [${event.targetHpAfter} HP]")
                renderHp[event.targetId] = event.targetHpAfter
                // Attacker just acted — reset its cooldown
                renderCooldown[event.attackerId] = event.attackerType.cooldown
                flashUnitId = event.targetId; flashTimer = 0.3f; flashColor = Color.RED
                val tx = gridOffsetX + event.targetPos.x * cellSize + cellSize / 2
                val ty = gridOffsetY + event.targetPos.y * cellSize + cellSize / 2
                val ax = gridOffsetX + event.attackerPos.x * cellSize + cellSize / 2
                val ay = gridOffsetY + event.attackerPos.y * cellSize + cellSize / 2
                when (event.attackerType) {
                    is NormalUnitType.Melee   -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.5f) }
                    is NormalUnitType.Ranged  -> { battleEffects.addArrow(ax, ay, tx, ty); SoundGenerator.getArrowShot().play(0.4f) }
                    is MonsterUnitType.Bear   -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.7f) }
                    is MonsterUnitType.Wolf   -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.55f) }
                    is NormalUnitType.Healer  -> battleEffects.addSlash(tx, ty, false)
                    is SpecialUnitType.Farmer -> {}
                    is StructureUnitType.Farm -> {}
                }
            }
            is BattleEvent.Heal -> {
                battleLog.add("${event.healerName} heals ${event.targetName} +${event.amount} [${event.targetHpAfter} HP]")
                renderHp[event.targetId] = event.targetHpAfter
                // Healer just acted — reset its cooldown
                renderCooldown[event.healerId] = allUnitsById[event.healerId]?.type?.cooldown ?: 0
                flashUnitId = event.targetId; flashTimer = 0.3f; flashColor = Color.GREEN
                val tx = gridOffsetX + event.targetPos.x * cellSize + cellSize / 2
                val ty = gridOffsetY + event.targetPos.y * cellSize + cellSize / 2
                battleEffects.addHealGlow(tx, ty); SoundGenerator.getHealChime().play(0.4f)
            }
            is BattleEvent.Death -> {
                battleLog.add("${event.unitName} died!")
                deadUnits.add(event.unitId); SoundGenerator.getDeath().play(0.5f)
            }
            is BattleEvent.FarmPlanted -> {
                battleLog.add("${event.farmerName} planted a Farm at (${event.position.x},${event.position.y})")
                // Farmer just acted — reset its cooldown
                renderCooldown[event.farmerId] = allUnitsById[event.farmerId]?.type?.cooldown ?: 0
                // Register the dynamically spawned Farm unit for rendering
                val farm = BattleUnit(id = event.farmId, type = StructureUnitType.Farm, owner = BattleUnit.Owner.PLAYER, position = event.position)
                registerUnit(farm)
                flashUnitId = event.farmId; flashTimer = 0.4f; flashColor = Color(0.4f, 1f, 0.3f, 1f)
            }
            is BattleEvent.FarmGold -> {
                battleLog.add("Farm +${event.amount}g")
                farmGoldEarned += event.amount
                flashUnitId = event.farmId; flashTimer = 0.25f; flashColor = Color(1f, 0.9f, 0.1f, 1f)
                refreshCommanderPanel()
            }
        }
    }

    private fun smoothStep(t: Float): Float = t * t * (3f - 2f * t)

    // ─── Input (drag-and-drop) ───────────────────────────────────────────────────

    private fun createInputProcessor() = object : com.badlogic.gdx.InputAdapter() {

        override fun touchDown(screenX: Int, screenY: Int, pointer: Int, button: Int): Boolean {
            val worldY = Gdx.graphics.height - screenY.toFloat()

            if (phase == Phase.SETUP) {
                // Check roster bar click → start drag
                val slotType = getRosterSlotAt(screenX.toFloat(), worldY)
                if (slotType != null) {
                    // If we can afford it, start dragging
                    if (gold >= slotType.cost) {
                        draggingType = slotType
                        dragScreenX = screenX.toFloat()
                        dragScreenY = worldY
                        isDragging = true
                    }
                    return true
                }

                // Check placed player unit click → remove + refund
                val gridX = ((screenX - gridOffsetX) / cellSize).toInt()
                val gridY = ((worldY - gridOffsetY) / cellSize).toInt()
                if (gridX in 0..BattleGrid.PLAYER_ZONE_END && gridY in 0 until grid.height) {
                    val unit = grid.unitAt(Position(gridX, gridY))
                    if (unit != null && unit.owner == BattleUnit.Owner.PLAYER) {
                        removePlayerUnit(unit)
                        rebuildUI()
                        return true
                    }
                }
            }
            return false
        }

        override fun touchDragged(screenX: Int, screenY: Int, pointer: Int): Boolean {
            if (!isDragging) return false
            val worldY = Gdx.graphics.height - screenY.toFloat()
            dragScreenX = screenX.toFloat()
            dragScreenY = worldY
            hoverGridX = ((screenX - gridOffsetX) / cellSize).toInt()
            hoverGridY = ((worldY - gridOffsetY) / cellSize).toInt()
            return true
        }

        override fun touchUp(screenX: Int, screenY: Int, pointer: Int, button: Int): Boolean {
            if (!isDragging) return false
            val worldY = Gdx.graphics.height - screenY.toFloat()
            val gridX = ((screenX - gridOffsetX) / cellSize).toInt()
            val gridY = ((worldY - gridOffsetY) / cellSize).toInt()
            val pos = Position(gridX, gridY)
            val type = draggingType

            if (type != null && gridX in 0..BattleGrid.PLAYER_ZONE_END && gridY in 0 until grid.height
                && grid.getTile(pos).placeable && !grid.isOccupied(pos)
            ) {
                // Place unit and deduct gold
                val unit = BattleUnit(id = nextUnitId++, type = type, owner = BattleUnit.Owner.PLAYER, position = pos)
                grid.placeUnit(unit)
                registerUnit(unit)
                placedPlayerUnitIds.add(unit.id)
                gold -= type.cost
                refreshCommanderPanel()
            }

            draggingType = null
            isDragging = false
            hoverGridX = -1
            hoverGridY = -1
            rebuildUI()
            return true
        }
    }

    private fun getRosterSlotAt(sx: Float, sy: Float): UnitType? {
        if (sy !in rosterBarY..(rosterBarY + rosterBarH)) return null
        for ((i, type) in shopTypes.withIndex()) {
            val slotX = rosterStartX + i * (rosterSlotSize + 12f) + 12f
            val slotY = rosterBarY + (rosterBarH - rosterSlotSize) / 2
            if (sx in slotX..(slotX + rosterSlotSize) && sy in slotY..(slotY + rosterSlotSize)) return type
        }
        return null
    }

    private fun removePlayerUnit(unit: BattleUnit) {
        gold += unit.type.cost
        refreshCommanderPanel()
        placedPlayerUnitIds.remove(unit.id)
        allUnitsById.remove(unit.id)
        renderPositions.remove(unit.id)
        renderHp.remove(unit.id)
        grid.removeUnit(unit)
    }

    // ─── UI Buttons ─────────────────────────────────────────────────────────────

    private fun rebuildUI() {
        stage.clear()
        val skin = createSkin()
        val table = Table().apply { setFillParent(true); bottom().right().pad(20f) }

        when (phase) {
            Phase.SETUP -> {
                val hasUnits = placedPlayerUnitIds.isNotEmpty()
                if (hasUnits) {
                    val startBtn = TextButton("START BATTLE", skin)
                    startBtn.addListener(object : ClickListener() {
                        override fun clicked(event: InputEvent?, x: Float, y: Float) { startBattle() }
                    })
                    table.add(startBtn).width(200f).height(55f).pad(8f).row()
                }
                val backBtn = TextButton("BACK TO MENU", skin)
                backBtn.addListener(object : ClickListener() {
                    override fun clicked(event: InputEvent?, x: Float, y: Float) {
                        if (commander != null) game.screen = CampaignScreen(game)
                        else game.screen = MainMenuScreen(game)
                    }
                })
                table.add(backBtn).width(200f).height(45f).pad(8f)
            }
            Phase.BATTLE -> {
                // Speed controls — visible and clickable during playback
                table.add(Label("Speed", skin)).padBottom(6f).row()
                for (speed in PlaybackSpeed.entries) {
                    val isActive = speed == playbackSpeed
                    val btn = TextButton(speed.label, skin, if (isActive) "speedActive" else "default")
                    btn.addListener(object : ClickListener() {
                        override fun clicked(event: InputEvent?, x: Float, y: Float) {
                            if (playbackSpeed != speed) {
                                playbackSpeed = speed
                                rebuildUI()
                            }
                        }
                    })
                    table.add(btn).width(130f).height(40f).padBottom(4f).row()
                }
            }
            Phase.RESULT -> {
                val outcome = battleOutcome!!
                val won = outcome.winner == BattleOutcome.Winner.PLAYER

                val resultText = when (outcome.winner) {
                    BattleOutcome.Winner.PLAYER -> "VICTORY!"
                    BattleOutcome.Winner.ENEMY  -> "DEFEAT"
                    else                        -> "DRAW"
                }
                table.add(TextButton(resultText, skin)).width(200f).height(55f).pad(8f).row()

                if (commander != null) {
                    // ── Campaign mode ──────────────────────────────────────────────
                    if (won) {
                        val next      = updatedCommander!!
                        val leveledUp = next.level > commander.level

                        // Reward breakdown
                        val farmLine = if (farmGoldEarned > 0) "   farms +${farmGoldEarned}g" else ""
                        table.add(TextButton(
                            "${enemyKillCount} kills  +${enemyKillCount * GOLD_PER_KILL}g   bonus +${scenario.goldReward}g${farmLine}   hired -${initialGold - gold}g",
                            skin
                        )).width(360f).height(36f).pad(4f).row()
                        table.add(TextButton(
                            "+${scenario.xpReward} XP" + (if (leveledUp) "   ⬆ Level ${next.level}!" else ""),
                            skin
                        )).width(260f).height(36f).pad(4f).row()

                        // New unlocks
                        val newUnlocks = next.unlockedUnitTypeIds - commander.unlockedUnitTypeIds.toSet()
                        if (newUnlocks.isNotEmpty()) {
                            val names = newUnlocks.joinToString(", ") { id ->
                                runCatching { UnitType.fromId(id).displayName }.getOrDefault(id)
                            }
                            table.add(TextButton("Unlocked: $names!", skin))
                                .width(260f).height(36f).pad(4f).row()
                        }

                        val continueBtn = TextButton("CONTINUE", skin)
                        continueBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) {
                                game.commander = updatedCommander!!
                                game.saveManager.save(updatedCommander!!)
                                game.screen = CampaignScreen(game)
                            }
                        })
                        table.add(continueBtn).width(200f).height(55f).pad(8f).row()
                    }

                    val retryBtn = TextButton("RETRY", skin)
                    retryBtn.addListener(object : ClickListener() {
                        override fun clicked(event: InputEvent?, x: Float, y: Float) {
                            // Free retry — original commander state, no gold deducted
                            game.screen = BattleScreen(game, scenario, commander)
                        }
                    })
                    table.add(retryBtn).width(200f).height(45f).pad(8f).row()

                    val retreatBtn = TextButton("RETREAT TO CAMP", skin)
                    retreatBtn.addListener(object : ClickListener() {
                        override fun clicked(event: InputEvent?, x: Float, y: Float) {
                            if (!won) {
                                // Deduct gold spent on defeat when retreating
                                val spent = initialGold - gold
                                val penalised = commander.copy(gold = maxOf(0, commander.gold - spent))
                                game.commander = penalised
                                game.saveManager.save(penalised)
                            }
                            game.screen = CampaignScreen(game)
                        }
                    })
                    table.add(retreatBtn).width(200f).height(45f).pad(8f)

                } else {
                    // ── Tutorial / standalone mode ─────────────────────────────────
                    val hasNext = tutorialIndex in 0 until Scenarios.tutorialSequence.size - 1
                    if (won && hasNext) {
                        val nextBtn = TextButton("NEXT BATTLE", skin)
                        nextBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) {
                                game.screen = BattleScreen(game, Scenarios.tutorialSequence[tutorialIndex + 1])
                            }
                        })
                        table.add(nextBtn).width(200f).height(45f).pad(8f).row()
                    }

                    val retryBtn = TextButton("RETRY", skin)
                    retryBtn.addListener(object : ClickListener() {
                        override fun clicked(event: InputEvent?, x: Float, y: Float) {
                            game.screen = BattleScreen(game, scenario)
                        }
                    })
                    table.add(retryBtn).width(200f).height(45f).pad(8f).row()

                    val menuBtn = TextButton("MENU", skin)
                    menuBtn.addListener(object : ClickListener() {
                        override fun clicked(event: InputEvent?, x: Float, y: Float) { game.screen = MainMenuScreen(game) }
                    })
                    table.add(menuBtn).width(200f).height(45f).pad(8f)
                }
            }
        }

        stage.addActor(table)

        // Re-add the CommanderPanel after every stage clear — left sidebar, always on top
        val widget = commanderWidget
        if (widget != null) {
            val panelContainer = Table()
            panelContainer.setFillParent(true)
            panelContainer.top().left()
            panelContainer.add(widget).width(210f).fillY()
            stage.addActor(panelContainer)
        }
    }

    private fun createSkin(): Skin {
        val skin = Skin()
        val f = BitmapFont().apply { data.setScale(1.1f) }
        skin.add("default-font", f)
        val px = Pixmap(1, 1, Pixmap.Format.RGBA8888).apply { setColor(Color.WHITE); fill() }
        skin.add("white", Texture(px)); px.dispose()
        skin.add("default", TextButton.TextButtonStyle().apply {
            up   = skin.newDrawable("white", Color(0.2f,  0.3f,  0.2f,  1f))
            over = skin.newDrawable("white", Color(0.3f,  0.45f, 0.3f,  1f))
            down = skin.newDrawable("white", Color(0.12f, 0.2f,  0.12f, 1f))
            font = f; fontColor = Color.WHITE
        })
        // Active speed button — bright highlight so the current speed is obvious
        skin.add("speedActive", TextButton.TextButtonStyle().apply {
            up   = skin.newDrawable("white", Color(0.55f, 0.38f, 0.05f, 1f))
            over = skin.newDrawable("white", Color(0.7f,  0.5f,  0.08f, 1f))
            down = skin.newDrawable("white", Color(0.4f,  0.28f, 0.03f, 1f))
            font = f; fontColor = Color(1f, 0.9f, 0.3f, 1f)
        })
        // Label style for the "Speed" label above the buttons
        skin.add("default", Label.LabelStyle(f, Color.LIGHT_GRAY))
        return skin
    }

