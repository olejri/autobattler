    private fun startBattle() {        phase = Phase.BATTLE
        battleOutcome = engine.simulate(grid)
        battleEvents = battleOutcome!!.events
        currentEventIndex = 0
        eventTimer = 0f
        animating = false
        battleLog.clear()
        // All units start the battle ready to act (cooldown = 0)
        renderCooldown.clear()
        allUnitsById.keys.forEach { renderCooldown[it] = 0 }
        val logPath = BattleLogger.log(grid, battleOutcome!!, scenario.name)
        Gdx.app.log("Autobattler", "Battle log saved: $logPath")
        rebuildUI()
    }

    private fun updateBattleAnimation(delta: Float) {
        if (animating) {
            animProgress += delta / animDuration
            if (animProgress >= 1f) {
                renderPositions[animUnitId] = Vector2(animTo)
                animating = false
                if (currentEventIndex < battleEvents.size) {
                    val next = battleEvents[currentEventIndex]
                    if (next is BattleEvent.Move && next.unitId == animUnitId) { applyNextEvent(); return }
                }
            } else {
                val t = smoothStep(animProgress)
                renderPositions[animUnitId] = Vector2(MathUtils.lerp(animFrom.x, animTo.x, t), MathUtils.lerp(animFrom.y, animTo.y, t))
            }
            return
        }
        if (battleEffects.isPlaying) return
        eventTimer += delta
        if (eventTimer >= eventDelay && currentEventIndex < battleEvents.size) { eventTimer = 0f; applyNextEvent() }
        if (currentEventIndex >= battleEvents.size && !animating && !battleEffects.isPlaying && phase == Phase.BATTLE) {
            phase = Phase.RESULT
            when (battleOutcome?.winner) {
                BattleOutcome.Winner.PLAYER -> SoundGenerator.getVictory().play(0.6f)
                BattleOutcome.Winner.ENEMY  -> SoundGenerator.getDefeat().play(0.6f)
                else                        -> SoundGenerator.getDefeat().play(0.4f)
            }
            // Count enemy kills for gold drops
            enemyKillCount = battleOutcome!!.events
                .filterIsInstance<BattleEvent.Death>()
                .count { allUnitsById[it.unitId]?.owner == BattleUnit.Owner.ENEMY }

            // Compute updated commander now, but only commit when player clicks Continue
            if (commander != null) {
                val goldSpent  = initialGold - gold
                val goldEarned = enemyKillCount * GOLD_PER_KILL + scenario.goldReward + farmGoldEarned

                if (campUnits != null) {
                    // Camp ambush — always compute result so camp unit survival is tracked.
                    // Survivors are camp units whose corresponding BattleUnit is NOT in deadUnits.
                    val survivingCampUnits = campUnits.filterIndexed { idx, _ ->
                        val uid = campUnitIdByIndex[idx]
                        uid != null && uid !in deadUnits
                    }
                    val won = battleOutcome?.winner == BattleOutcome.Winner.PLAYER
                    updatedCommander = commander.afterCampAmbush(
                        xpReward          = if (won) scenario.xpReward else 0,
                        goldEarned        = if (won) goldEarned else enemyKillCount * GOLD_PER_KILL,
                        survivingCampUnits = survivingCampUnits
                    )
                } else if (battleOutcome?.winner == BattleOutcome.Winner.PLAYER) {
                    updatedCommander = if (scenario.progressesCampaign) {
                        commander.afterVictory(scenario.xpReward, goldEarned, goldSpent)
                    } else {
                        commander.afterBattleReward(scenario.xpReward, goldEarned, goldSpent)
                    }
                }
            }
            rebuildUI()
        }
    }

    private fun applyNextEvent() {
        if (currentEventIndex >= battleEvents.size) return
        when (val event = battleEvents[currentEventIndex++]) {
            is BattleEvent.TurnStart -> {
                battleLog.add("── Turn ${event.turnNumber} ──")
                // Tick all cooldown timers down by 1 (mirrors engine behaviour)
                for (id in renderCooldown.keys) {
                    renderCooldown[id] = ((renderCooldown[id] ?: 0) - 1).coerceAtLeast(0)
                }
            }
            is BattleEvent.Move -> {
                val isLast = currentEventIndex >= battleEvents.size || battleEvents[currentEventIndex] !is BattleEvent.Move
                    || (battleEvents[currentEventIndex] as BattleEvent.Move).unitId != event.unitId
                if (isLast) battleLog.add("${event.unitName} moves to (${event.to.x},${event.to.y})")
                animating = true; animUnitId = event.unitId
                animFrom = Vector2(event.from.x.toFloat(), event.from.y.toFloat())
                animTo = Vector2(event.to.x.toFloat(), event.to.y.toFloat()); animProgress = 0f
            }
            is BattleEvent.Attack -> {
                battleLog.add("${event.attackerName} deals ${event.damage} to ${event.targetName} [${event.targetHpAfter} HP]")
                renderHp[event.targetId] = event.targetHpAfter
                // Attacker just acted — reset its cooldown
                renderCooldown[event.attackerId] = event.attackerType.cooldown
                flashUnitId = event.targetId; flashTimer = 0.3f; flashColor = Color.RED
                val tx = gridOffsetX + event.targetPos.x * cellSize + cellSize / 2
                val ty = gridOffsetY + event.targetPos.y * cellSize + cellSize / 2
                val ax = gridOffsetX + event.attackerPos.x * cellSize + cellSize / 2
                val ay = gridOffsetY + event.attackerPos.y * cellSize + cellSize / 2
                when (event.attackerType) {
                    is NormalUnitType.Melee, is NormalUnitType.MeleeSilver, is NormalUnitType.MeleeGold,
                    is NormalUnitType.Knight, is NormalUnitType.KnightSilver, is NormalUnitType.KnightGold,
                    is NormalUnitType.GriffinRider, is NormalUnitType.GriffinRiderSilver, is NormalUnitType.GriffinRiderGold ->
                        { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.5f) }
                    is NormalUnitType.Ranged, is NormalUnitType.RangedSilver, is NormalUnitType.RangedGold ->
                        { battleEffects.addArrow(ax, ay, tx, ty); SoundGenerator.getArrowShot().play(0.4f) }
                    is MonsterUnitType.Bear   -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.7f) }
                    is MonsterUnitType.Wolf   -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.55f) }
                    is MonsterUnitType.Goblin -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.4f) }
                    is MonsterUnitType.Skeleton -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.5f) }
                    is MonsterUnitType.DarkMage -> { battleEffects.addArrow(ax, ay, tx, ty); SoundGenerator.getArrowShot().play(0.55f) }
                    is MonsterUnitType.Troll  -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.8f) }
                    is MonsterUnitType.Bandit -> { battleEffects.addArrow(ax, ay, tx, ty); SoundGenerator.getArrowShot().play(0.45f) }
                    is MonsterUnitType.OrcWarrior -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.6f) }
                    is MonsterUnitType.Spider -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.45f) }
                    is MonsterUnitType.Dragon -> { battleEffects.addSlash(tx, ty, event.attackerPos.x > event.targetPos.x); SoundGenerator.getSwordClash().play(0.9f) }
                    is NormalUnitType.Healer, is NormalUnitType.HealerSilver, is NormalUnitType.HealerGold -> battleEffects.addSlash(tx, ty, false)
                    is SpecialUnitType.Farmer, is SpecialUnitType.FarmerSilver, is SpecialUnitType.FarmerGold -> {}
                    is SpecialUnitType.Wizard, is SpecialUnitType.WizardSilver, is SpecialUnitType.WizardGold ->
                        { battleEffects.addArrow(ax, ay, tx, ty); SoundGenerator.getArrowShot().play(0.55f) }
                    is StructureUnitType.Farm, is StructureUnitType.Wall, is StructureUnitType.Gate -> {}
                    is StructureUnitType.Tower ->
                        { battleEffects.addArrow(ax, ay, tx, ty); SoundGenerator.getArrowShot().play(0.5f) }
                }
            }
            is BattleEvent.Heal -> {
                battleLog.add("${event.healerName} heals ${event.targetName} +${event.amount} [${event.targetHpAfter} HP]")
                renderHp[event.targetId] = event.targetHpAfter
                val healerType = allUnitsById[event.healerId]?.type
                if (healerType !is MonsterUnitType.Troll) {
                    renderCooldown[event.healerId] = healerType?.cooldown ?: 0
                }
                flashUnitId = event.targetId; flashTimer = 0.3f; flashColor = Color.GREEN
                val tx = gridOffsetX + event.targetPos.x * cellSize + cellSize / 2
                val ty = gridOffsetY + event.targetPos.y * cellSize + cellSize / 2
                battleEffects.addHealGlow(tx, ty); SoundGenerator.getHealChime().play(0.4f)
            }
            is BattleEvent.Death -> {
                battleLog.add("${event.unitName} died!")
                deadUnits.add(event.unitId); SoundGenerator.getDeath().play(0.5f)
            }
            is BattleEvent.FarmPlanted -> {
                battleLog.add("${event.farmerName} planted a Farm at (${event.position.x},${event.position.y})")
                // Farmer just acted — reset its cooldown
                renderCooldown[event.farmerId] = allUnitsById[event.farmerId]?.type?.cooldown ?: 0
                // Register the dynamically spawned Farm unit for rendering
                val farm = BattleUnit(id = event.farmId, type = StructureUnitType.Farm, owner = BattleUnit.Owner.PLAYER, position = event.position)
                registerUnit(farm)
                flashUnitId = event.farmId; flashTimer = 0.4f; flashColor = Color(0.4f, 1f, 0.3f, 1f)
            }
            is BattleEvent.FarmGold -> {
                battleLog.add("Farm +${event.amount}g")
                farmGoldEarned += event.amount
                flashUnitId = event.farmId; flashTimer = 0.25f; flashColor = Color(1f, 0.9f, 0.1f, 1f)
                refreshCommanderPanel()
            }
            is BattleEvent.Fireball -> {
                val hitsDesc = if (event.hits.isEmpty()) "missed!" else "${event.hits.size} unit(s) hit!"
                battleLog.add("${event.casterName} Fireball → (${event.targetTile.x},${event.targetTile.y})  $hitsDesc")
                // Update HP for every unit caught in the blast
                for (hit in event.hits) {
                    renderHp[hit.unitId] = hit.hpAfter
                }
                // Reset wizard cooldown
                renderCooldown[event.casterId] = event.casterType.cooldown
                // Explosion visual centred on the target tile, covering the blast radius
                val tx = gridOffsetX + event.targetTile.x * cellSize + cellSize / 2
                val ty = gridOffsetY + event.targetTile.y * cellSize + cellSize / 2
                val blastPx = cellSize * (event.radius + 0.5f)
                battleEffects.addExplosion(tx, ty, blastPx)
                SoundGenerator.getArrowShot().play(0.85f)
            }
            is BattleEvent.FireBreath -> {
                battleLog.add("${event.casterName} FIRE BREATH ${event.direction} — ${event.hits.size} hit(s)!")
                for (hit in event.hits) {
                    renderHp[hit.unitId] = hit.hpAfter
                }
                renderCooldown[event.casterId] = 10
                event.hits.lastOrNull()?.let {
                    flashUnitId = it.unitId
                    flashTimer = 0.5f
                    flashColor = Color(1f, 0.35f, 0f, 1f)
                }
                // Visualise every cone tile as an orange flame highlight
                val tileCenters = event.coneTiles.map { tile ->
                    Pair(
                        gridOffsetX + tile.x * cellSize + cellSize / 2,
                        gridOffsetY + tile.y * cellSize + cellSize / 2
                    )
                }
                battleEffects.addConeFlame(tileCenters, cellSize)
                SoundGenerator.getArrowShot().play(0.9f)
            }
            is BattleEvent.Cleave -> {
                battleLog.add("${event.attackerName} CLEAVE — ${event.splashHits.size + 1} units hit!")
                renderHp[event.primaryId] = event.primaryHpAfter
                for (s in event.splashHits) {
                    renderHp[s.unitId] = s.hpAfter
                }
                renderCooldown[event.attackerId] = allUnitsById[event.attackerId]?.type?.cooldown ?: 0
                flashUnitId = event.primaryId
                flashTimer = 0.35f
                flashColor = Color(1f, 0.2f, 0.2f, 1f)
                SoundGenerator.getArrowShot().play(0.7f)
            }
        }
    }

    private fun smoothStep(t: Float): Float = t * t * (3f - 2f * t)

    // ─── Input (drag-and-drop) ───────────────────────────────────────────────────

    private fun createInputProcessor() = object : com.badlogic.gdx.InputAdapter() {

        override fun touchDown(screenX: Int, screenY: Int, pointer: Int, button: Int): Boolean {
            val worldY = Gdx.graphics.height - screenY.toFloat()

            // ── Right-click: show tooltip for unit or tile ────────────────────
            if (button == Input.Buttons.RIGHT) {
                val gridX = ((screenX - gridOffsetX) / cellSize).toInt()
                val gridY = ((worldY - gridOffsetY) / cellSize).toInt()
                if (gridX in 0 until grid.width && gridY in 0 until grid.height) {
                    val anchorX = gridOffsetX + (gridX + 1) * cellSize
                    val anchorY = gridOffsetY + gridY * cellSize
                    // Prefer unit over tile if one is present
                    val unit = allUnitsById.values.firstOrNull { u ->
                        u.id !in deadUnits && u.occupies(Position(gridX, gridY))
                    }
                    if (unit != null) {
                        showUnitTooltip(unit, anchorX, anchorY)
                    } else {
                        showTileTooltip(grid.getTile(gridX, gridY), anchorX, anchorY)
                    }
                } else {
                    dismissTooltip()
                }
                return true
            }

            // ── Left-click: dismiss tooltip, then process normal input ────────
            dismissTooltip()

            if (phase == Phase.SETUP) {
                // Check scroll arrows first
                if (tryRosterArrowClick(screenX.toFloat(), worldY)) return true

                // Check roster bar click → start drag
                val slotType = getRosterSlotAt(screenX.toFloat(), worldY)
                if (slotType != null) {
                    // If we can afford it, start dragging
                    if (gold >= slotType.cost) {
                        draggingType = slotType
                        dragScreenX = screenX.toFloat()
                        dragScreenY = worldY
                        isDragging = true
                    }
                    return true
                }

                // Check placed player unit click → remove + refund
                val gridX = ((screenX - gridOffsetX) / cellSize).toInt()
                val gridY = ((worldY - gridOffsetY) / cellSize).toInt()
                if (isPlayerSide(gridX, gridY)) {
                    val unit = grid.unitAt(Position(gridX, gridY))
                    if (unit != null && unit.owner == BattleUnit.Owner.PLAYER) {
                        removePlayerUnit(unit)
                        rebuildUI()
                        return true
                    }
                }
            }
            return false
        }

        override fun touchDragged(screenX: Int, screenY: Int, pointer: Int): Boolean {
            if (!isDragging) return false
            val worldY = Gdx.graphics.height - screenY.toFloat()
            dragScreenX = screenX.toFloat()
            dragScreenY = worldY
            hoverGridX = ((screenX - gridOffsetX) / cellSize).toInt()
            hoverGridY = ((worldY - gridOffsetY) / cellSize).toInt()
            return true
        }

        override fun touchUp(screenX: Int, screenY: Int, pointer: Int, button: Int): Boolean {
            if (!isDragging) return false
            val worldY = Gdx.graphics.height - screenY.toFloat()
            val gridX = ((screenX - gridOffsetX) / cellSize).toInt()
            val gridY = ((worldY - gridOffsetY) / cellSize).toInt()
            val pos = Position(gridX, gridY)
            val type = draggingType

            if (type != null && isPlayerSide(gridX, gridY)
                && grid.getTile(pos).placeable && !grid.isOccupied(pos)
            ) {
                // Place unit and deduct gold
                val unit = BattleUnit(id = nextUnitId++, type = type, owner = BattleUnit.Owner.PLAYER, position = pos)
                grid.placeUnit(unit)
                registerUnit(unit)
                placedPlayerUnitIds.add(unit.id)
                gold -= type.cost
                refreshCommanderPanel()
            }

            draggingType = null
            isDragging = false
            hoverGridX = -1
            hoverGridY = -1
            rebuildUI()
            return true
        }

        override fun scrolled(amountX: Float, amountY: Float): Boolean {
            if (phase == Phase.SETUP && shopTypes.size > maxVisibleRosterSlots) {
                val maxOffset = shopTypes.size - maxVisibleRosterSlots
                rosterScrollOffset = (rosterScrollOffset + amountY.toInt()).coerceIn(0, maxOffset)
                return true
            }
            return false
        }
    }

    private fun getRosterSlotAt(sx: Float, sy: Float): UnitType? {
        if (sy !in rosterBarY..(rosterBarY + rosterBarH)) return null
        val barX = rosterStartX
        val barW = grid.width * cellSize
        val needsScroll = shopTypes.size > maxVisibleRosterSlots
        val arrowW = if (needsScroll) rosterArrowW else 0f
        val slotsAreaX = barX + arrowW
        val slotsAreaEnd = barX + barW - arrowW

        // Don't register hits on arrow buttons
        if (needsScroll && (sx < slotsAreaX || sx > slotsAreaEnd)) return null

        val visCount = minOf(maxVisibleRosterSlots, shopTypes.size - rosterScrollOffset)
        for (vi in 0 until visCount) {
            val slotX = slotsAreaX + vi * (rosterSlotSize + 12f) + 12f
            val slotY = rosterBarY + (rosterBarH - rosterSlotSize) / 2
            if (sx in slotX..(slotX + rosterSlotSize) && sy in slotY..(slotY + rosterSlotSize))
                return shopTypes[rosterScrollOffset + vi]
        }
        return null
    }

    /** Returns true if sx,sy landed on a scroll arrow. Scrolls and returns true if so. */
    private fun tryRosterArrowClick(sx: Float, sy: Float): Boolean {
        if (sy !in rosterBarY..(rosterBarY + rosterBarH)) return false
        if (!( shopTypes.size > maxVisibleRosterSlots)) return false
        val barX = rosterStartX
        val barW = grid.width * cellSize
        val maxOffset = shopTypes.size - maxVisibleRosterSlots
        if (sx in barX..(barX + rosterArrowW)) {
            if (rosterScrollOffset > 0) rosterScrollOffset--
            return true
        }
        if (sx in (barX + barW - rosterArrowW)..(barX + barW)) {
            if (rosterScrollOffset < maxOffset) rosterScrollOffset++
            return true
        }
        return false
    }

    private fun removePlayerUnit(unit: BattleUnit) {
        gold += unit.type.cost
        refreshCommanderPanel()
        placedPlayerUnitIds.remove(unit.id)
        allUnitsById.remove(unit.id)
        renderPositions.remove(unit.id)
        renderHp.remove(unit.id)
        grid.removeUnit(unit)
    }

    // ─── UI Buttons ─────────────────────────────────────────────────────────────

    private fun rebuildUI() {
        stage.clear()
        val skin = createSkin()
        val table = Table().apply { setFillParent(true); bottom().right().pad(20f) }

        when (phase) {
            Phase.SETUP -> {
                val hasUnits = placedPlayerUnitIds.isNotEmpty()
                if (hasUnits) {
                    val startBtn = TextButton("START BATTLE", skin)
                    startBtn.addListener(object : ClickListener() {
                        override fun clicked(event: InputEvent?, x: Float, y: Float) { startBattle() }
                    })
                    table.add(startBtn).width(200f).height(55f).pad(8f).row()
                }
                val backBtn = TextButton("BACK TO MENU", skin)
                backBtn.addListener(object : ClickListener() {
                    override fun clicked(event: InputEvent?, x: Float, y: Float) {
                        if (commander != null) game.screen = CampaignScreen(game)
                        else game.screen = MainMenuScreen(game)
                    }
                })
                table.add(backBtn).width(200f).height(45f).pad(8f)
            }
            Phase.BATTLE -> {
                // Speed controls — visible and clickable during playback
                table.add(Label("Speed", skin)).padBottom(6f).row()
                for (speed in PlaybackSpeed.entries) {
                    val isActive = speed == playbackSpeed
                    val btn = TextButton(speed.label, skin, if (isActive) "speedActive" else "default")
                    btn.addListener(object : ClickListener() {
                        override fun clicked(event: InputEvent?, x: Float, y: Float) {
                            if (playbackSpeed != speed) {
                                playbackSpeed = speed
                                rebuildUI()
                            }
                        }
                    })
                    table.add(btn).width(130f).height(40f).padBottom(4f).row()
                }
            }
            Phase.RESULT -> {
                val outcome = battleOutcome!!
                val won = outcome.winner == BattleOutcome.Winner.PLAYER

                val resultText = when (outcome.winner) {
                    BattleOutcome.Winner.PLAYER -> "VICTORY!"
                    BattleOutcome.Winner.ENEMY  -> "DEFEAT"
                    else                        -> "DRAW"
                }
                table.add(TextButton(resultText, skin)).width(200f).height(55f).pad(8f).row()

                // ── Rogue mode ───────────────────────────────────────────────────
                if (onRogueNodeWin != null) {
                    if (won) {
                        val killGold = enemyKillCount * GOLD_PER_KILL
                        table.add(TextButton(
                            "${enemyKillCount} kills  +${killGold}g" +
                            if (farmGoldEarned > 0) "   farms +${farmGoldEarned}g" else "",
                            skin
                        )).width(360f).height(36f).pad(4f).row()

                        val continueBtn = TextButton("CONTINUE", skin)
                        continueBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) {
                                onRogueNodeWin.invoke(killGold, farmGoldEarned)
                            }
                        })
                        table.add(continueBtn).width(200f).height(55f).pad(8f).row()
                    } else {
                        table.add(TextButton("Your run is over.", skin))
                            .width(280f).height(36f).pad(4f).row()
                        val endBtn = TextButton("END RUN", skin)
                        endBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) {
                                onRogueNodeLose?.invoke()
                            }
                        })
                        table.add(endBtn).width(200f).height(55f).pad(8f).row()
                    }
                    // Rogue mode: no other buttons — return early
                    stage.addActor(table)
                    return
                }

                if (commander != null) {
                    if (campUnits != null) {
                        // ── Camp ambush mode ───────────────────────────────────────────
                        // updatedCommander always computed (win or lose) — it contains
                        // the updated camp roster (dead units removed, survivors kept).
                        val next = updatedCommander!!
                        val survivorCount = next.campUnits.size
                        val lostCount = campUnits.size - survivorCount

                        // Camp status
                        table.add(TextButton(
                            "Camp survivors: $survivorCount / ${campUnits.size}   (lost: $lostCount)",
                            skin
                        )).width(360f).height(36f).pad(4f).row()

                        if (won) {
                            table.add(TextButton(
                                "${enemyKillCount} kills  +${enemyKillCount * GOLD_PER_KILL}g   bonus +${scenario.goldReward}g   +${scenario.xpReward} XP",
                                skin
                            )).width(360f).height(36f).pad(4f).row()
                            val leveledUp = next.level > commander.level
                            if (leveledUp) {
                                table.add(TextButton("⬆ Level ${next.level}!", skin))
                                    .width(200f).height(36f).pad(4f).row()
                            }
                        } else {
                            val killGold = enemyKillCount * GOLD_PER_KILL
                            table.add(TextButton(
                                "Kill gold: +${killGold}g   (no victory bonus on defeat)",
                                skin
                            )).width(360f).height(36f).pad(4f).row()
                        }

                        // CONTINUE always available — commits surviving camp units
                        val continueBtn = TextButton("CONTINUE", skin)
                        continueBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) {
                                game.commander = next
                                game.saveManager.save(next)
                                game.screen = CampaignScreen(game)
                            }
                        })
                        table.add(continueBtn).width(200f).height(55f).pad(8f).row()

                        // RETRY — replays camp ambush with the original camp (all units at full HP)
                        val retryBtn = TextButton("RETRY", skin)
                        retryBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) {
                                game.screen = BattleScreen(game, scenario, commander, campUnits = campUnits)
                            }
                        })
                        table.add(retryBtn).width(200f).height(45f).pad(8f)

                    } else {
                    // ── Campaign mode ──────────────────────────────────────────────
                    if (won) {
                        val next      = updatedCommander!!
                        val leveledUp = next.level > commander.level

                        // Reward breakdown
                        val farmLine = if (farmGoldEarned > 0) "   farms +${farmGoldEarned}g" else ""
                        table.add(TextButton(
                            "${enemyKillCount} kills  +${enemyKillCount * GOLD_PER_KILL}g   bonus +${scenario.goldReward}g${farmLine}   hired -${initialGold - gold}g",
                            skin
                        )).width(360f).height(36f).pad(4f).row()
                        table.add(TextButton(
                            "+${scenario.xpReward} XP" + (if (leveledUp) "   ⬆ Level ${next.level}!" else ""),
                            skin
                        )).width(260f).height(36f).pad(4f).row()

                        // New unlocks
                        val newUnlocks = next.unlockedUnitTypeIds - commander.unlockedUnitTypeIds.toSet()
                        if (newUnlocks.isNotEmpty()) {
                            val names = newUnlocks.joinToString(", ") { id ->
                                runCatching { UnitType.fromId(id).displayName }.getOrDefault(id)
                            }
                            table.add(TextButton("Unlocked: $names!", skin))
                                .width(260f).height(36f).pad(4f).row()
                        }

                        val continueBtn = TextButton("CONTINUE", skin)
                        continueBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) {
                                game.commander = updatedCommander!!
                                game.saveManager.save(updatedCommander!!)
                                game.screen = CampaignScreen(game)
                            }
                        })
                        table.add(continueBtn).width(200f).height(55f).pad(8f).row()
                    }

                    val retryBtn = TextButton("RETRY", skin)
                    retryBtn.addListener(object : ClickListener() {
                        override fun clicked(event: InputEvent?, x: Float, y: Float) {
                            // Free retry — original commander state, no gold deducted
                            game.screen = BattleScreen(game, scenario, commander)
                        }
                    })
                    table.add(retryBtn).width(200f).height(45f).pad(8f).row()

                    val retreatBtn = TextButton("RETREAT TO CAMP", skin)
                    retreatBtn.addListener(object : ClickListener() {
                        override fun clicked(event: InputEvent?, x: Float, y: Float) {
                            if (!won) {
                                // Deduct gold spent on defeat when retreating
                                val spent = initialGold - gold
                                val penalised = commander.copy(gold = maxOf(0, commander.gold - spent))
                                game.commander = penalised
                                game.saveManager.save(penalised)
                            }
                            game.screen = CampaignScreen(game)
                        }
                    })
                    table.add(retreatBtn).width(200f).height(45f).pad(8f)
                    } // end campaign mode else-block
                } else {
                    // ── Tutorial / standalone / sandbox mode ──────────────────────
                    val hasNext = tutorialIndex in 0 until Scenarios.tutorialSequence.size - 1
                    if (won && hasNext) {
                        val nextBtn = TextButton("NEXT BATTLE", skin)
                        nextBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) {
                                game.screen = BattleScreen(game, Scenarios.tutorialSequence[tutorialIndex + 1])
                            }
                        })
                        table.add(nextBtn).width(200f).height(45f).pad(8f).row()
                    }

                    if (onBattleEnd != null) {
                        // Sandbox mode — go back to sandbox setup
                        val backBtn = TextButton("BACK TO SANDBOX", skin)
                        backBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) { onBattleEnd.invoke() }
                        })
                        table.add(backBtn).width(220f).height(45f).pad(8f)
                    } else {
                        val retryBtn = TextButton("RETRY", skin)
                        retryBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) {
                                game.screen = BattleScreen(game, scenario)
                            }
                        })
                        table.add(retryBtn).width(200f).height(45f).pad(8f).row()

                        val menuBtn = TextButton("MENU", skin)
                        menuBtn.addListener(object : ClickListener() {
                            override fun clicked(event: InputEvent?, x: Float, y: Float) { game.screen = MainMenuScreen(game) }
                        })
                        table.add(menuBtn).width(200f).height(45f).pad(8f)
                    }
                }
            }
        }

        stage.addActor(table)

        // Re-add the CommanderPanel after every stage clear — left sidebar, always on top
        val widget = commanderWidget
        if (widget != null) {
            val panelContainer = Table()
            panelContainer.setFillParent(true)
            panelContainer.top().left()
            panelContainer.add(widget).width(210f).fillY()
            stage.addActor(panelContainer)
        }
    }

    private fun createSkin(): Skin {
        val skin = Skin()
        val f = BitmapFont().apply { data.setScale(1.1f) }
        skin.add("default-font", f)
        val px = Pixmap(1, 1, Pixmap.Format.RGBA8888).apply { setColor(Color.WHITE); fill() }
        skin.add("white", Texture(px)); px.dispose()
        skin.add("default", TextButton.TextButtonStyle().apply {
            up   = skin.newDrawable("white", Color(0.2f,  0.3f,  0.2f,  1f))
            over = skin.newDrawable("white", Color(0.3f,  0.45f, 0.3f,  1f))
            down = skin.newDrawable("white", Color(0.12f, 0.2f,  0.12f, 1f))
            font = f; fontColor = Color.WHITE
        })
        // Active speed button — bright highlight so the current speed is obvious
        skin.add("speedActive", TextButton.TextButtonStyle().apply {
            up   = skin.newDrawable("white", Color(0.55f, 0.38f, 0.05f, 1f))
            over = skin.newDrawable("white", Color(0.7f,  0.5f,  0.08f, 1f))
            down = skin.newDrawable("white", Color(0.4f,  0.28f, 0.03f, 1f))
            font = f; fontColor = Color(1f, 0.9f, 0.3f, 1f)
        })
        // Label style for the "Speed" label above the buttons
        skin.add("default", Label.LabelStyle(f, Color.LIGHT_GRAY))
        return skin
    }

