/**
 * Main battle screen handling three phases in a single unified view:
 *
 * 1. SETUP   — Player sees enemy placements, drags units from the roster bar
 *              (below the map) onto their side, spending gold.
 * 2. BATTLE  — Events replay with animated unit movement.
 * 3. RESULT  — Outcome shown with retry/next options.
 *
 * When [commander] is provided the screen is in campaign mode:
 * the shop is filtered to unlocked units, and a win awards XP + gold to the Commander.
 */
class BattleScreen(
    private val game: AutobattlerGame,
    private val scenario: ScenarioDefinition,
    private val commander: Commander? = null,
    private val boughtRoster: List<UnitType>? = null,  // null = buy phase active
    private val onBattleEnd: (() -> Unit)? = null,     // sandbox: called instead of going to menu
    /**
     * When non-null, this is a camp ambush: the listed units were pre-placed from the camp
     * and the screen must track which survive to update Commander.campUnits afterwards.
     */
    private val campUnits: List<CampUnit>? = null,
    /**
     * Rogue-mode callbacks. When set the screen is in rogue-run context:
     * - [onRogueNodeWin]  called on PLAYER victory with (goldFromKills, goldFromFarms)
     * - [onRogueNodeLose] called on ENEMY victory (permadeath — run ends)
     * - [rogueShopUnitIds] overrides the default shop roster for this battle
     */
    private val onRogueNodeWin:  ((goldFromKills: Int, goldFromFarms: Int) -> Unit)? = null,
    private val onRogueNodeLose: (() -> Unit)? = null,
    private val rogueShopUnitIds: List<String>? = null
) : ScreenAdapter() {

    private enum class Phase { SETUP, BATTLE, RESULT }

    // ─── Core state ─────────────────────────────────────────────────────────────
    private val grid = BattleGrid()
    private val engine = GridBattleEngine()

    // Index within tutorialSequence (-1 if campaign or standalone scenario)
    private val tutorialIndex = Scenarios.tutorialSequence.indexOf(scenario)

    // ─── Rendering ──────────────────────────────────────────────────────────────
    private val shapeRenderer = ShapeRenderer()
    private val batch = SpriteBatch()
    // Fonts created lazily in show() after GL context is ready
    private lateinit var font: BitmapFont
    private lateinit var bigFont: BitmapFont
    private val stage = Stage(ScreenViewport())

    // ─── Grid layout ─────────────────────────────────────────────────────────────
    // gridOffsetX leaves 220px on the left for the CommanderPanel sidebar
    private val cellSize = 48f
    private val gridOffsetX = 220f
    private val gridOffsetY = 185f   // leaves 185px at bottom for roster bar

    // ─── SETUP state ────────────────────────────────────────────────────────────
    private var phase = Phase.SETUP

    /** Starting gold: commander's persistent pool in campaign mode, scenario budget otherwise. */
    private val initialGold = commander?.gold ?: scenario.startingGold
    private var gold = initialGold

    // Units available in the shop — filtered by unlocked types in campaign mode,
    // or overridden by the rogueShopUnitIds when in rogue mode
    private val shopTypes = when {
        rogueShopUnitIds != null ->
            rogueShopUnitIds.mapNotNull { runCatching { UnitType.fromId(it) }.getOrNull() }
                .filterIsInstance<UnitType>()
        commander != null ->
            UnitType.purchasable.filter { it.id in commander.unlockedUnitTypeIds }
        else ->
            listOf(NormalUnitType.Melee, NormalUnitType.Ranged, NormalUnitType.Healer)
    }

    // Campaign result — computed on victory, committed when player clicks Continue
    private var updatedCommander: Commander? = null

    // Track how many enemy units were killed (for gold drops)
    private var enemyKillCount = 0
    // Track gold generated by Farm structures during battle
    private var farmGoldEarned = 0

    companion object {
        const val GOLD_PER_KILL     = 10
        const val BATTLE_BONUS_GOLD = 200  // included in scenario.goldReward
    }

    /** Units available to drag onto the map (counts per type). */
    private val rosterPool: MutableMap<UnitType, Int> =
        shopTypes.associateWith { 0 }.toMutableMap()

    // Commander panel widget — shown top-right in campaign mode
    private var commanderWidget: CommanderPanel? = null

    // Drag-and-drop state
    private var draggingType: UnitType? = null
    private var dragScreenX = 0f
    private var dragScreenY = 0f
    private var isDragging = false

    // Grid cell highlight under cursor during drag
    private var hoverGridX = -1
    private var hoverGridY = -1

    /** Units the player has placed (to allow removal/refund). */
    private val placedPlayerUnitIds = mutableListOf<Int>()

    /** Maps camp unit index → BattleUnit ID for survival tracking in camp ambushes. */
    private val campUnitIdByIndex = mutableMapOf<Int, Int>()

    private var nextUnitId = 1

    // ─── Animation state ────────────────────────────────────────────────────────
    private val renderPositions = mutableMapOf<Int, Vector2>()
    private val renderHp = mutableMapOf<Int, Int>()
    private val renderCooldown = mutableMapOf<Int, Int>()   // current cooldownTimer per unit
    private val deadUnits = mutableSetOf<Int>()
    private val allUnitsById = mutableMapOf<Int, BattleUnit>()

    // ─── Playback speed ─────────────────────────────────────────────────────────
    private enum class PlaybackSpeed(val label: String, val multiplier: Float) {
        SLOW("Slow", 1f), FASTER("Faster", 2f), FASTEST("Fastest", 4f)
    }
    private var playbackSpeed = PlaybackSpeed.SLOW

    // ─── Battle playback ────────────────────────────────────────────────────────
    private var battleOutcome: BattleOutcome? = null
    private var battleEvents: List<BattleEvent> = emptyList()
    private var currentEventIndex = 0
    private var eventTimer = 0f
    private val eventDelay   get() = 0.5f / playbackSpeed.multiplier
    private val animDuration get() = 0.2f / playbackSpeed.multiplier

    private var animating = false
    private var animUnitId = -1
    private var animFrom = Vector2()
    private var animTo = Vector2()
    private var animProgress = 0f

    // ─── Tooltip state ───────────────────────────────────────────────────────────
    private var tooltipVisible = false
    private var tooltipTitle = ""
    private var tooltipLines = listOf<String>()
    private var tooltipAnchorX = 0f
    private var tooltipAnchorY = 0f

    // ─── Flash effects ──────────────────────────────────────────────────────────
    private var flashUnitId = -1
    private var flashTimer = 0f
    private var flashColor = Color.WHITE

    // ─── Battle effects & log ───────────────────────────────────────────────────
    private val battleEffects = BattleEffects()
    private val battleLog = mutableListOf<String>()

    // ─── Roster bar layout ───────────────────────────────────────────────────────
    private val rosterBarY = 10f
    private val rosterBarH = 160f
    private val rosterSlotSize = 110f
    private val rosterStartX = gridOffsetX  // left-aligned under the grid
    private val rosterArrowW = 36f          // width of each </> scroll button
    private var rosterScrollOffset = 0      // index of first visible slot

    /** How many roster slots fit side-by-side between the two arrows. */
    private val maxVisibleRosterSlots: Int get() {
        val barW = grid.width * cellSize
        val usable = barW - rosterArrowW * 2
        return maxOf(1, (usable / (rosterSlotSize + 12f)).toInt())
    }


    // ─── Lifecycle ──────────────────────────────────────────────────────────────

    override fun show() {
        Gdx.input.inputProcessor = InputMultiplexer(stage, createInputProcessor())

        // Create crisp FreeType fonts — must be after GL context is ready
        font = Fonts.create(18, borderWidth = 1f)
        bigFont = Fonts.create(28, borderWidth = 1.5f)

        // Load map — sandbox tileOverrides take priority, then mapPath, then default layout
        if (scenario.tileOverrides != null) {
            for ((pos, type) in scenario.tileOverrides) {
                grid.setTile(pos, type)
            }
        } else if (scenario.mapPath != null) {
            try {
                val mapDef = MapLoader.loadMap(scenario.mapPath)
                MapLoader.applyToGrid(mapDef, grid)
            } catch (e: Exception) {
                MapLayouts.applyTutorialLayout(grid)
            }
        } else {
            MapLayouts.applyTutorialLayout(grid)
        }

        // Place enemy units
        for ((type, pos) in scenario.enemyPlacements) {
            val unit = BattleUnit(id = nextUnitId++, type = type, owner = BattleUnit.Owner.ENEMY, position = pos)
            grid.placeUnit(unit)
            registerUnit(unit)
        }

        // Sandbox: pre-place player and natural units, then go straight to battle
        if (scenario.playerPlacements != null) {
            for ((idx, placement) in scenario.playerPlacements.withIndex()) {
                val (type, pos) = placement
                val unit = BattleUnit(id = nextUnitId++, type = type, owner = BattleUnit.Owner.PLAYER, position = pos)
                grid.placeUnit(unit)
                registerUnit(unit)
                placedPlayerUnitIds.add(unit.id)
                // Track camp unit index → unit ID so we can detect survivors after the battle
                if (campUnits != null && idx < campUnits.size) {
                    campUnitIdByIndex[idx] = unit.id
                }
            }
            for ((type, pos) in scenario.naturalPlacements.orEmpty()) {
                val unit = BattleUnit(id = nextUnitId++, type = type, owner = BattleUnit.Owner.NATURAL, position = pos)
                grid.placeUnit(unit)
                registerUnit(unit)
            }
            startBattle()
            rebuildUI()
            return
        }

        // If bypassing buy (dev quick-test), pre-populate the rosterPool from scenario default
        if (boughtRoster != null) {
            for (type in boughtRoster) {
                rosterPool[type] = (rosterPool[type] ?: 0) + 1
            }
        }

        // Commander panel — pinned to the LEFT side, consistent with CampaignScreen
        if (commander != null) {
            commanderWidget = CommanderPanel(commander)
            val panelContainer = Table()
            panelContainer.setFillParent(true)
            panelContainer.top().left()
            panelContainer.add(commanderWidget!!).width(210f).fillY()
            stage.addActor(panelContainer)
        }

        rebuildUI()
    }

    private fun registerUnit(unit: BattleUnit) {
        allUnitsById[unit.id] = unit
        renderPositions[unit.id] = Vector2(unit.position.x.toFloat(), unit.position.y.toFloat())
        renderHp[unit.id] = unit.currentHp
    }

    // ─── Render ─────────────────────────────────────────────────────────────────

    override fun render(delta: Float) {
        Gdx.gl.glClearColor(0.06f, 0.06f, 0.1f, 1f)
        Gdx.gl.glClear(GL20.GL_COLOR_BUFFER_BIT)

        if (phase == Phase.BATTLE) updateBattleAnimation(delta)
        if (flashTimer > 0f) flashTimer -= delta
        battleEffects.update(delta)

        drawGrid()
        drawUnits()

        Gdx.gl.glEnable(GL20.GL_BLEND)
        Gdx.gl.glBlendFunc(GL20.GL_SRC_ALPHA, GL20.GL_ONE_MINUS_SRC_ALPHA)
        battleEffects.render(shapeRenderer)
        Gdx.gl.glDisable(GL20.GL_BLEND)

        if (phase == Phase.SETUP) {
            drawRosterBar()
            drawDragGhost()
        }

        drawHUD()

        if (tooltipVisible) drawTooltip()

        stage.act(delta)
        stage.draw()
    }

    // ─── Grid drawing ───────────────────────────────────────────────────────────

    private fun drawGrid() {
        shapeRenderer.begin(ShapeRenderer.ShapeType.Filled)
        for (x in 0 until grid.width) {
            for (y in 0 until grid.height) {
                val sx = gridOffsetX + x * cellSize
                val sy = gridOffsetY + y * cellSize
                val tile = grid.getTile(x, y)
                shapeRenderer.color = getTileColor(tile, isPlayerSide(x, y))
                shapeRenderer.rect(sx, sy, cellSize, cellSize)

                when (tile) {
                    TileType.WATER -> {
                        shapeRenderer.color = Color(0.15f, 0.3f, 0.55f, 1f)
                        val wo = ((x + y) % 3) * 4f
                        shapeRenderer.rect(sx + 4f + wo, sy + cellSize / 2 - 1f, cellSize * 0.4f, 2f)
                    }
                    TileType.ROCK -> {
                        shapeRenderer.color = Color(0.35f, 0.32f, 0.28f, 1f)
                        shapeRenderer.circle(sx + cellSize / 2, sy + cellSize / 2, cellSize * 0.3f)
                        shapeRenderer.color = Color(0.45f, 0.42f, 0.38f, 1f)
                        shapeRenderer.circle(sx + cellSize / 2 - 2f, sy + cellSize / 2 + 2f, cellSize * 0.18f)
                    }
                    TileType.BRIDGE -> {
                        shapeRenderer.color = Color(0.5f, 0.35f, 0.15f, 1f)
                        for (i in 0..3) {
                            val py = sy + 4f + i * (cellSize - 8f) / 3f
                            shapeRenderer.rect(sx + 3f, py, cellSize - 6f, 3f)
                        }
                    }
                    TileType.TREE -> {
                        shapeRenderer.color = Color(0.35f, 0.22f, 0.08f, 1f)
                        shapeRenderer.rect(sx + cellSize / 2 - 3f, sy + 2f, 6f, cellSize * 0.4f)
                        shapeRenderer.color = Color(0.1f, 0.4f, 0.12f, 1f)
                        shapeRenderer.circle(sx + cellSize / 2, sy + cellSize * 0.65f, cellSize * 0.32f)
                        shapeRenderer.color = Color(0.15f, 0.5f, 0.15f, 1f)
                        shapeRenderer.circle(sx + cellSize / 2 - 3f, sy + cellSize * 0.7f, cellSize * 0.2f)
                    }
                    TileType.SAND -> {
                        // Subtle dune ripple lines
                        shapeRenderer.color = Color(0.45f, 0.36f, 0.14f, 0.6f)
                        shapeRenderer.rect(sx + 6f, sy + cellSize * 0.35f, cellSize * 0.55f, 2f)
                        shapeRenderer.rect(sx + 10f, sy + cellSize * 0.65f, cellSize * 0.45f, 2f)
                    }
                    TileType.MUD -> {
                        // Dark splotch
                        shapeRenderer.color = Color(0.25f, 0.18f, 0.08f, 0.7f)
                        shapeRenderer.circle(sx + cellSize * 0.35f, sy + cellSize * 0.4f, cellSize * 0.18f)
                        shapeRenderer.circle(sx + cellSize * 0.65f, sy + cellSize * 0.6f, cellSize * 0.14f)
                    }
                    TileType.SHALLOW_WATER -> {
                        shapeRenderer.color = Color(0.2f, 0.45f, 0.65f, 0.7f)
                        shapeRenderer.rect(sx + 3f, sy + cellSize / 2 - 1f, cellSize * 0.5f, 2f)
                        shapeRenderer.rect(sx + 8f, sy + cellSize * 0.65f, cellSize * 0.35f, 2f)
                    }
                    TileType.FORT -> {
                        // Stone brick pattern
                        shapeRenderer.color = Color(0.4f, 0.38f, 0.34f, 1f)
                        shapeRenderer.rect(sx + 3f, sy + cellSize / 2 - 1f, cellSize - 6f, 3f)
                        shapeRenderer.rect(sx + 3f, sy + cellSize * 0.75f - 1f, cellSize - 6f, 3f)
                        shapeRenderer.color = Color(0.35f, 0.32f, 0.28f, 1f)
                        shapeRenderer.rect(sx + 3f, sy + cellSize * 0.25f - 1f, cellSize * 0.45f, 3f)
                        shapeRenderer.rect(sx + cellSize * 0.55f, sy + cellSize * 0.25f - 1f, cellSize * 0.4f, 3f)
                    }
                    TileType.LAVA -> {
                        // Orange glowing lava flow
                        shapeRenderer.color = Color(1f, 0.45f, 0.02f, 0.9f)
                        shapeRenderer.circle(sx + cellSize * 0.4f, sy + cellSize * 0.45f, cellSize * 0.22f)
                        shapeRenderer.color = Color(1f, 0.7f, 0.1f, 0.8f)
                        shapeRenderer.circle(sx + cellSize * 0.6f, sy + cellSize * 0.6f, cellSize * 0.14f)
                    }
                    TileType.ICE -> {
                        // Icy crystal sheen
                        shapeRenderer.color = Color(0.55f, 0.75f, 0.9f, 0.7f)
                        shapeRenderer.rect(sx + 4f, sy + cellSize * 0.3f, cellSize - 8f, 2f)
                        shapeRenderer.rect(sx + 8f, sy + cellSize * 0.6f, cellSize - 16f, 2f)
                    }
                    TileType.RUINS -> {
                        // Crumbled stone chunks
                        shapeRenderer.color = Color(0.42f, 0.36f, 0.3f, 0.8f)
                        shapeRenderer.rect(sx + 4f, sy + 4f, cellSize * 0.3f, cellSize * 0.25f)
                        shapeRenderer.rect(sx + cellSize * 0.55f, sy + cellSize * 0.6f, cellSize * 0.35f, cellSize * 0.28f)
                        shapeRenderer.color = Color(0.3f, 0.26f, 0.22f, 0.6f)
                        shapeRenderer.rect(sx + 4f, sy + cellSize * 0.65f, cellSize * 0.25f, cellSize * 0.2f)
                    }
                    else -> {}
                }
            }
        }

        // Hover highlight during drag
        if (isDragging && hoverGridX in 0 until grid.width && hoverGridY in 0 until grid.height
            && isPlayerSide(hoverGridX, hoverGridY)) {
            val pos = Position(hoverGridX, hoverGridY)
            val canPlace = draggingType != null && grid.getTile(pos).placeable && !grid.isOccupied(pos)
            shapeRenderer.color = if (canPlace) Color(0.3f, 0.7f, 0.3f, 0.5f) else Color(0.7f, 0.2f, 0.2f, 0.4f)
            shapeRenderer.rect(
                gridOffsetX + hoverGridX * cellSize + 1,
                gridOffsetY + hoverGridY * cellSize + 1,
                cellSize - 2, cellSize - 2
            )
        }
        shapeRenderer.end()

        // Grid lines
        shapeRenderer.begin(ShapeRenderer.ShapeType.Line)
        shapeRenderer.color = Color(0.2f, 0.2f, 0.25f, 1f)
        for (x in 0..grid.width) {
            val sx = gridOffsetX + x * cellSize
            shapeRenderer.line(sx, gridOffsetY, sx, gridOffsetY + grid.height * cellSize)
        }
        for (y in 0..grid.height) {
            val sy = gridOffsetY + y * cellSize
            shapeRenderer.line(gridOffsetX, sy, gridOffsetX + grid.width * cellSize, sy)
        }
        // Territory border — thick yellow edges where player territory meets enemy territory
        shapeRenderer.color = Color(0.85f, 0.85f, 0.2f, 0.8f)
        for (x in 0 until grid.width) {
            for (y in 0 until grid.height) {
                if (!isPlayerSide(x, y)) continue
                val sx = gridOffsetX + x * cellSize
                val sy = gridOffsetY + y * cellSize
                if (!isPlayerSide(x + 1, y)) shapeRenderer.line(sx + cellSize, sy, sx + cellSize, sy + cellSize)
                if (!isPlayerSide(x - 1, y)) shapeRenderer.line(sx, sy, sx, sy + cellSize)
                if (!isPlayerSide(x, y + 1)) shapeRenderer.line(sx, sy + cellSize, sx + cellSize, sy + cellSize)
                if (!isPlayerSide(x, y - 1)) shapeRenderer.line(sx, sy, sx + cellSize, sy)
            }
        }
        shapeRenderer.end()
    }

    private fun getTileColor(tile: TileType, playerSide: Boolean): Color = when (tile) {
        TileType.GRASS         -> if (playerSide) Color(0.08f, 0.16f, 0.08f, 1f) else Color(0.16f, 0.08f, 0.08f, 1f)
        TileType.WATER         -> Color(0.08f, 0.15f, 0.35f, 1f)
        TileType.ROCK          -> Color(0.25f, 0.22f, 0.2f,  1f)
        TileType.BRIDGE        -> Color(0.35f, 0.25f, 0.1f,  1f)
        TileType.TREE          -> Color(0.05f, 0.12f, 0.05f, 1f)
        TileType.SAND          -> if (playerSide) Color(0.28f, 0.22f, 0.08f, 1f) else Color(0.32f, 0.2f,  0.06f, 1f)
        TileType.MUD           -> if (playerSide) Color(0.14f, 0.12f, 0.06f, 1f) else Color(0.18f, 0.1f,  0.04f, 1f)
        TileType.SHALLOW_WATER -> Color(0.1f,  0.22f, 0.4f,  1f)
        TileType.FORT          -> Color(0.22f, 0.2f,  0.18f, 1f)
        TileType.LAVA          -> Color(0.5f,  0.1f,  0.02f, 1f)
        TileType.ICE           -> if (playerSide) Color(0.18f, 0.32f, 0.52f, 1f) else Color(0.22f, 0.22f, 0.42f, 1f)
        TileType.RUINS         -> if (playerSide) Color(0.18f, 0.15f, 0.12f, 1f) else Color(0.22f, 0.14f, 0.1f,  1f)
    }

    /** True when (x,y) belongs to the player placement zone. Uses custom territory if provided. */
    private fun isPlayerSide(x: Int, y: Int): Boolean {
        if (x !in 0 until grid.width || y !in 0 until grid.height) return false
        return scenario.playerTerritory?.contains(Position(x, y)) ?: (x <= BattleGrid.PLAYER_ZONE_END)
    }

    // ─── Unit drawing ───────────────────────────────────────────────────────────

    private fun drawUnits() {
        shapeRenderer.begin(ShapeRenderer.ShapeType.Filled)
        for ((unitId, renderPos) in renderPositions) {
            if (unitId in deadUnits) continue
            val unit = allUnitsById[unitId] ?: continue
            val uc = unit.size.toFloat()
            val cx = gridOffsetX + renderPos.x * cellSize + cellSize * uc / 2
            val cy = gridOffsetY + renderPos.y * cellSize + cellSize * uc / 2
            val radius = cellSize * uc * 0.42f

            var color = when (unit.owner) {
                BattleUnit.Owner.PLAYER  -> Color(0.2f, 0.6f, 1f, 0.6f)
                BattleUnit.Owner.ENEMY   -> Color(1f, 0.3f, 0.2f, 0.6f)
                BattleUnit.Owner.NATURAL -> Color(0.6f, 0.45f, 0.1f, 0.6f)  // amber — neutral predator
            }
            if (unitId == flashUnitId && flashTimer > 0f) {
                val t = flashTimer / 0.3f
                color = Color(MathUtils.lerp(color.r, flashColor.r, t), MathUtils.lerp(color.g, flashColor.g, t), MathUtils.lerp(color.b, flashColor.b, t), 1f)
            }
            shapeRenderer.color = color
            shapeRenderer.circle(cx, cy, radius)
            shapeRenderer.color = Color(0.08f, 0.08f, 0.12f, 1f)
            shapeRenderer.circle(cx, cy, radius - 3f)

            val hp = renderHp[unitId] ?: unit.currentHp
            val barW = cellSize * uc - 6f
            val barH = 5f
            val bx = gridOffsetX + renderPos.x * cellSize + 3f
            val by = gridOffsetY + renderPos.y * cellSize + cellSize * uc - 8f
            shapeRenderer.color = Color(0.15f, 0.15f, 0.15f, 1f)
            shapeRenderer.rect(bx, by, barW, barH)
            val hp01 = hp.toFloat() / unit.type.maxHp
            shapeRenderer.color = when { hp01 > 0.6f -> Color(0.2f, 0.8f, 0.2f, 1f); hp01 > 0.3f -> Color(0.9f, 0.8f, 0.1f, 1f); else -> Color(0.9f, 0.2f, 0.2f, 1f) }
            shapeRenderer.rect(bx, by, barW * hp01, barH)

            // Cooldown / readiness bar (battle phase only; skip structures which never act)
            if (phase == Phase.BATTLE && !unit.type.isStructure) {
                val maxCd = unit.type.cooldown
                val curCd = renderCooldown[unitId] ?: 0
                val ready01 = if (maxCd <= 0) 1f else (maxCd - curCd).toFloat() / maxCd
                val cby = by - 6f
                shapeRenderer.color = Color(0.1f, 0.1f, 0.1f, 1f)
                shapeRenderer.rect(bx, cby, barW, 4f)
                shapeRenderer.color = if (ready01 >= 1f) Color(1f, 0.85f, 0f, 1f) else Color(0.2f, 0.75f, 0.9f, 1f)
                shapeRenderer.rect(bx, cby, barW * ready01, 4f)
            }

            // In setup phase: show remove [X] indicator on placed player units
            if (phase == Phase.SETUP && unit.owner == BattleUnit.Owner.PLAYER) {
                shapeRenderer.color = Color(0.8f, 0.2f, 0.2f, 0.7f)
                shapeRenderer.circle(gridOffsetX + renderPos.x * cellSize + cellSize - 6f, gridOffsetY + renderPos.y * cellSize + cellSize - 6f, 6f)
            }
        }
        shapeRenderer.end()

        batch.begin()
        for ((unitId, renderPos) in renderPositions) {
            if (unitId in deadUnits) continue
            val unit = allUnitsById[unitId] ?: continue
            val uc = unit.size.toFloat()
            val ss = cellSize * uc - 8f
            val sx = gridOffsetX + renderPos.x * cellSize + (cellSize * uc - ss) / 2
            val sy = gridOffsetY + renderPos.y * cellSize + (cellSize * uc - ss) / 2 - 2f
            batch.setColor(when (unit.owner) {
                BattleUnit.Owner.ENEMY   -> Color(1f, 0.6f, 0.6f, 1f)
